#!/usr/bin/env node
// Copies a Wayglim export into the docs as two plain modules the Vue wrapper
// (docs/.vitepress/WayglimBackground.vue) can import:
//   docs/.vitepress/wayglim/generated/settings.js  the studio settings, background and aspect ratio
//   docs/.vitepress/wayglim/generated/engine.js    the engine (mountWayglim), byte for byte
// then captures the hero's still fallback images from them (scripts/capture-wayglim-fallback.mjs, needs Chrome).
// Accepts both export formats from the studio's Export → Code menu:
//   - HTML (wayglim-background.html): engine script + settings script
//   - Next.js / React (WayglimBackground.tsx): engine section + WAYGLIM_SETTINGS
// Nothing is rewritten: the engine and the settings are copied verbatim; only `export` lines (and, for the HTML
// engine, the closure the React export wraps it in) are added. Re-run after exporting a new look:
//   pnpm sync-wayglim ~/Downloads/wayglim-background.html
import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const source = process.argv[2];
if (!source) {
  console.error('Usage: pnpm sync-wayglim <path to wayglim-background.html or WayglimBackground.tsx>');
  process.exit(1);
}

const text = readFileSync(source, 'utf8');
const outDir = join(dirname(fileURLToPath(import.meta.url)), '../docs/.vitepress/wayglim/generated');

const between = (startMarker, endMarker) => {
  const start = text.indexOf(startMarker);
  const end = endMarker ? text.indexOf(endMarker, start) : text.length;
  if (start < 0 || end < 0) throw new Error(`Could not find "${startMarker}" in ${source}. Is it a Wayglim export?`);
  return text.slice(start, end).trimEnd();
};

let settingsModule;
let engine;

if (text.includes('window.Wayglim')) {
  // HTML export
  const settings = text.match(/var settings = (\{.*?\});\n/)?.[1];
  const noise = text.match(/settings\.noise = ("[^"]*");/)?.[1];
  const background = text.match(/data-wayglim="[^"]+" style="[^"]*background:([^;"]+)/)?.[1]?.trim();
  if (!settings || !noise) throw new Error(`Could not find the settings in ${source}. Is it a Wayglim export?`);
  settingsModule =
    `const WAYGLIM_SETTINGS = ${settings};\nWAYGLIM_SETTINGS.noise = ${noise};\n\n` +
    `const WAYGLIM_BACKGROUND = ${JSON.stringify(background ?? 'transparent')};\n` +
    'const WAYGLIM_ASPECT = WAYGLIM_SETTINGS.aspectRatio;\n';
  engine = `const mountWayglim = (() => {\n${between('const PAPER_GRAIN_NOISE_GLSL=', '\n  var api = { mount: mountCfMotion };')}\nreturn mountCfMotion;\n})();`;
} else {
  // Next.js / React export
  settingsModule =
    `${between('const WAYGLIM_SETTINGS = {', 'const WAYGLIM_BACKGROUND')}\n\n` +
    `${between('const WAYGLIM_BACKGROUND', '\n')}\n${between('const WAYGLIM_ASPECT', '\n')}\n`;
  engine = between('const mountWayglim = (() => {');
}

const header = (what) =>
  `// Generated by scripts/sync-wayglim.mjs from ${basename(source)} (${what}). Do not edit: re-export from the\n` +
  '// Wayglim studio and run `pnpm sync-wayglim <file>` instead.\n';

mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, 'settings.js'),
  `${header('studio settings')}${settingsModule}\nexport { WAYGLIM_ASPECT, WAYGLIM_BACKGROUND, WAYGLIM_SETTINGS };\n`,
);
writeFileSync(join(outDir, 'engine.js'), `${header('engine, verbatim')}${engine}\n\nexport default mountWayglim;\n`);
console.log(`Wayglim synced from ${source} into ${outDir}`);

const capture = spawnSync(
  process.execPath,
  [join(dirname(fileURLToPath(import.meta.url)), 'capture-wayglim-fallback.mjs')],
  {
    stdio: 'inherit',
  },
);
if (capture.status !== 0) {
  console.warn('The hero fallback images were not updated: run `pnpm wayglim-fallback` before committing.');
  process.exitCode = 1;
}
